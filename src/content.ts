export const normalize = (text: string) =>
  text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase()
export function itemPath(section: string, slug: string) {
  if (section === "dao-tao" && slug === "don-vi") return "/don-vi"
  if (section === "sinh-vien" && slug === "bieu-mau") return "/van-ban"
  return `/${section}/${slug}`
}
